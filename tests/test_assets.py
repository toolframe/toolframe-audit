"""Authoring contracts and bundled assets must match the read surfaces."""

from importlib.resources import files

from toolframe_sdk import validate

from toolframe_audit import outbox_migration
from toolframe_audit.plugin import INGEST_INPUT, LIST_OUTPUT, plugin


def test_contracts_scopes_and_packaged_assets():
    assert plugin.id == "audit" and plugin.kind == "business"
    assert plugin.provider_kind is None
    methods = plugin.services["audit.events"].methods
    assert methods["ingest"].audience == "internal"
    assert not methods["ingest"].required_scopes
    assert methods["list_events"].required_scopes == ("audit.read",)
    assert methods["list_events"].read_only
    assert methods["prune_events"].required_scopes == ("system.plugins.manage",)
    assert methods["prune_events"].audience == "system"
    assert not any(method.public_api for method in methods.values())
    for resource in plugin.resources:
        assert resource.required_scopes == ("audit.read",)
        if resource.kind == "llms.document":
            assert (
                files(resource.data["package"])
                .joinpath(resource.data["path"])
                .read_text()
            )
        if resource.kind == "mcp.tool":
            assert resource.data["method"] == "list_events"
    assert (
        "GENERATED BY DEFAULT AS IDENTITY"
        in plugin.store.migrations[0].for_dialect("postgresql").sql
    )
    assert "CREATE TABLE audit_outbox" in outbox_migration().for_dialect("sqlite").sql
    assert outbox_migration().for_dialect("postgresql").sql


def test_empty_output_matches_contract_and_ingest_has_no_identity_override():
    validate(LIST_OUTPUT, {"events": [], "count": 0, "limit": 50, "next_before": None})
    event_properties = INGEST_INPUT["properties"]["event"]["properties"]
    assert not {"source_owner", "application_id", "principal", "delivery_actor"} & set(
        event_properties
    )
    assert INGEST_INPUT["additionalProperties"] is False
